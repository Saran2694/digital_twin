package com.datamint.twin.dto;

import jakarta.validation.constraints.NotBlank;
import jakarta.validation.constraints.NotNull;
import java.time.LocalDate;
import java.time.LocalDateTime;
import java.util.List;

/** All request / response objects of the REST API. */
public final class Dtos {
    private Dtos() {}

    public record LoginRequest(@NotBlank String username, @NotBlank String password) {}
    public record UserInfo(Long id, String username, String fullName, String role, boolean enabled) {}
    public record LoginResponse(String token, UserInfo user) {}
    public record UserForm(String username, String password, String fullName, String role, Boolean enabled) {}

    public record DashboardSummary(int total, int running, int warning, int offline, long activeAlerts, LocalDate asOf) {}

    public record MachineSummary(Long id, String code, String name, String machineType, String line, String material,
                                 String status, String statusReason, Double temperature, Double moldTemp,
                                 Double pressure, Double runningHours, LocalDateTime lastUpdated,
                                 Double defectRate, long openAlerts, Double posX, Double posY) {}
    public record MachineUpdate(String name, String machineType, Double posX, Double posY) {}
    public record TrendPoint(String label, double temperature, double pressure) {}

    public record AlertView(Long id, Long machineId, String machineName, String type, String severity, String title,
                            String message, String componentId, String status, LocalDateTime createdAt,
                            String acknowledgedBy, LocalDateTime resolvedAt) {}
    public record PageResult<T>(List<T> items, long total, int page, int size) {}

    public record MaintenanceView(Long id, Long machineId, String machineName, String title, String description,
                                  String priority, String status, String requestedBy, String assignedTo,
                                  boolean autoGenerated, LocalDateTime createdAt, LocalDate dueDate,
                                  LocalDateTime completedAt) {}
    public record MaintenanceForm(@NotNull Long machineId, @NotBlank String title, String description,
                                  String priority, String assignedTo, LocalDate dueDate) {}

    public record Overview(long total, long good, long damaged, double yieldPct, long scrap, long rework,
                           double avgCycle, double avgPourTemp, double avgPressure, LocalDate from, LocalDate to) {}
    public record GroupRow(String name, long total, long damaged, double avgPourTemp, double avgPressure, double avgCycle) {}
    public record TrendRow(String period, long total, long damaged, double avgPourTemp, double avgPressure) {}

    public record ImportResult(int rows, int machines, int alertsCreated) {}
    public record AdminStats(long components, long machines, long alerts, long maintenance, long users) {}
}
