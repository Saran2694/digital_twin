package com.datamint.twin.service;

import com.datamint.twin.dto.Dtos.MachineSummary;
import com.datamint.twin.dto.Dtos.MaintenanceForm;
import com.datamint.twin.dto.Dtos.MaintenanceView;
import com.datamint.twin.model.Machine;
import com.datamint.twin.model.MaintenanceRequest;
import com.datamint.twin.repository.MachineRepository;
import com.datamint.twin.repository.MaintenanceRepository;
import org.springframework.data.domain.Sort;
import org.springframework.http.HttpStatus;
import org.springframework.stereotype.Service;
import org.springframework.web.server.ResponseStatusException;
import java.time.LocalDate;
import java.time.LocalDateTime;
import java.util.*;

@Service
public class MaintenanceService {
    private static final Set<String> STATUSES = Set.of("PENDING", "IN_PROGRESS", "COMPLETED");
    private static final Set<String> PRIORITIES = Set.of("LOW", "MEDIUM", "HIGH");

    private final MaintenanceRepository repo;
    private final MachineRepository machines;
    private final MonitoringService monitoring;

    public MaintenanceService(MaintenanceRepository repo, MachineRepository machines, MonitoringService monitoring) {
        this.repo = repo; this.machines = machines; this.monitoring = monitoring;
    }

    public List<MaintenanceView> list(String status, int limit) {
        Map<Long, String> names = names();
        return repo.findAll(Sort.by(Sort.Direction.DESC, "createdAt")).stream()
                .filter(r -> status == null || status.equals(r.getStatus()))
                .limit(limit > 0 ? limit : Long.MAX_VALUE)
                .map(r -> view(r, names)).toList();
    }

    public MaintenanceView create(MaintenanceForm f, String user) {
        MaintenanceRequest r = new MaintenanceRequest();
        apply(r, f);
        r.setStatus("PENDING");
        r.setRequestedBy(user);
        r.setCreatedAt(LocalDateTime.now());
        return view(repo.save(r), names());
    }

    public MaintenanceView update(Long id, MaintenanceForm f) {
        MaintenanceRequest r = find(id);
        apply(r, f);
        return view(repo.save(r), names());
    }

    public MaintenanceView setStatus(Long id, String status) {
        if (!STATUSES.contains(status)) throw new ResponseStatusException(HttpStatus.BAD_REQUEST, "Invalid status");
        MaintenanceRequest r = find(id);
        r.setStatus(status);
        r.setCompletedAt("COMPLETED".equals(status) ? LocalDateTime.now() : null);
        return view(repo.save(r), names());
    }

    public void delete(Long id) { repo.delete(find(id)); }

    /** Creates a PENDING request for every machine that is currently in WARNING / OFFLINE state. */
    public int autoGenerate() {
        int created = 0;
        for (MachineSummary s : monitoring.summaries()) {
            if ("RUNNING".equals(s.status())) continue;
            if (repo.existsByMachineIdAndAutoGeneratedAndStatusIn(s.id(), true, List.of("PENDING", "IN_PROGRESS"))) continue;
            String reason = s.statusReason();
            MaintenanceRequest r = new MaintenanceRequest();
            r.setMachineId(s.id());
            r.setTitle(reason.contains("temperature") ? "Check furnace / pour temperature control"
                    : reason.contains("critical") ? "Inspect mold for critical defects"
                    : "OFFLINE".equals(s.status()) ? "Restore machine data feed" : "Review defect rate");
            r.setDescription(reason);
            r.setPriority("OFFLINE".equals(s.status()) ? "HIGH" : "MEDIUM");
            r.setStatus("PENDING");
            r.setRequestedBy("system");
            r.setAutoGenerated(true);
            r.setCreatedAt(LocalDateTime.now());
            r.setDueDate(LocalDate.now().plusDays(3));
            repo.save(r);
            created++;
        }
        return created;
    }

    private void apply(MaintenanceRequest r, MaintenanceForm f) {
        if (!machines.existsById(f.machineId())) throw new ResponseStatusException(HttpStatus.BAD_REQUEST, "Unknown machine");
        r.setMachineId(f.machineId());
        r.setTitle(f.title());
        r.setDescription(f.description());
        r.setPriority(f.priority() != null && PRIORITIES.contains(f.priority()) ? f.priority() : "MEDIUM");
        r.setAssignedTo(f.assignedTo());
        r.setDueDate(f.dueDate());
    }

    private MaintenanceRequest find(Long id) {
        return repo.findById(id).orElseThrow(() -> new ResponseStatusException(HttpStatus.NOT_FOUND, "Request not found"));
    }

    private Map<Long, String> names() {
        Map<Long, String> m = new HashMap<>();
        for (Machine x : machines.findAll()) m.put(x.getId(), x.getName());
        return m;
    }

    private MaintenanceView view(MaintenanceRequest r, Map<Long, String> names) {
        return new MaintenanceView(r.getId(), r.getMachineId(), names.get(r.getMachineId()), r.getTitle(),
                r.getDescription(), r.getPriority(), r.getStatus(), r.getRequestedBy(), r.getAssignedTo(),
                r.isAutoGenerated(), r.getCreatedAt(), r.getDueDate(), r.getCompletedAt());
    }
}
