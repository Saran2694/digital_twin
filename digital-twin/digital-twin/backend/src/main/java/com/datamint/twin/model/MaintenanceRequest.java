package com.datamint.twin.model;

import jakarta.persistence.*;
import lombok.Getter;
import lombok.NoArgsConstructor;
import lombok.Setter;
import java.time.LocalDate;
import java.time.LocalDateTime;

@Entity
@Table(name = "maintenance_request")
@Getter @Setter @NoArgsConstructor
public class MaintenanceRequest {
    @Id @GeneratedValue(strategy = GenerationType.IDENTITY)
    private Long id;
    @Column(name = "machine_id", nullable = false) private Long machineId;
    @Column(nullable = false, length = 150) private String title;
    @Column(length = 600) private String description;
    @Column(length = 10) private String priority;      // LOW, MEDIUM, HIGH
    @Column(length = 15) private String status;        // PENDING, IN_PROGRESS, COMPLETED
    @Column(name = "requested_by", length = 60) private String requestedBy;
    @Column(name = "assigned_to", length = 60) private String assignedTo;
    @Column(name = "auto_generated") private boolean autoGenerated;
    @Column(name = "created_at") private LocalDateTime createdAt;
    @Column(name = "due_date") private LocalDate dueDate;
    @Column(name = "completed_at") private LocalDateTime completedAt;
}
